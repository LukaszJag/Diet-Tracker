package com.lukaszjag.diet_tracker_android.tools.sql_tools;

public class QueryMaker {
    public static String getAllProductTableLikeProductNameCaseInsensitive(String productData) {
        String escapedData = productData != null ? productData.replace("'", "''") : "";
        return "SELECT * FROM [diet_tracker_schema].[product_table] WHERE LOWER(product_name) LIKE '%" + escapedData + "%'";
    }

    public static String getAllProductsFromCalendarTableLikeDate(String date) {
        String escapedDate = date != null ? date.replace("'", "''") : "";
        return "SELECT * FROM [diet_tracker_schema].[calendar] WHERE day_date LIKE '%" + escapedDate + "%'";
    }

    // --- NOTES QUERIES ---

    // Fetches only ACTIVE notes (not deleted and not done)
    public static String getAllNotesQuery() {
        return "SELECT * FROM [diet_tracker_schema].[notes] WHERE (is_deleted = 0 OR is_deleted IS NULL) AND (is_done = 0 OR is_done IS NULL)";
    }

    // Fetches all HISTORY notes (either marked as done or deleted)
    public static String getAllHistoryNotesQuery() {
        return "SELECT * FROM [diet_tracker_schema].[notes] WHERE is_deleted = 1 OR is_done = 1";
    }

    // Mark note as done
    public static String markNoteAsDoneQuery(long id) {
        return "SET NOCOUNT ON; UPDATE [diet_tracker_schema].[notes] SET [is_done] = 1 WHERE [id] = " + id + "; SELECT 1 AS success;";
    }

    // Mark note as deleted (Soft delete)
    public static String markNoteAsDeletedQuery(long id) {
        return "SET NOCOUNT ON; UPDATE [diet_tracker_schema].[notes] SET [is_deleted] = 1 WHERE [id] = " + id + "; SELECT 1 AS success;";
    }

    // Restore note back to active
    public static String restoreNoteQuery(long id) {
        return "SET NOCOUNT ON; UPDATE [diet_tracker_schema].[notes] SET [is_deleted] = 0, [is_done] = 0 WHERE [id] = " + id + "; SELECT 1 AS success;";
    }

    // Permanent deletion from database
    public static String deleteNotePermanentlyQuery(long id) {
        return "SET NOCOUNT ON; DELETE FROM [diet_tracker_schema].[notes] WHERE [id] = " + id + "; SELECT 1 AS success;";
    }

    public static String insertNoteQuery(String title, String subtitle, String description,
                                         String category, String subcategory,
                                         boolean isUrgently, boolean isLearning, boolean isGeneral,
                                         boolean isToday, boolean isToBuy, String created, String deadline) {

        String safeTitle = title != null ? title.replace("'", "''") : "";
        String safeSub = subtitle != null ? subtitle.replace("'", "''") : "";
        String safeDesc = description != null ? description.replace("'", "''") : "";
        String safeCat = category != null ? category.replace("'", "''") : "";
        String safeSubcat = subcategory != null ? subcategory.replace("'", "''") : "";

        return "INSERT INTO [diet_tracker_schema].[notes] " +
                "([title], [subtitle], [description], [category], [subcategory], [is_urgently], [is_learning], " +
                "[is_general_to_do], [is_today_task], [is_to_buy_task], [is_done], [is_deleted], [date_created], [date_deadline]) " +
                "VALUES (" +
                "N'" + safeTitle + "', " +
                "N'" + safeSub + "', " +
                "N'" + safeDesc + "', " +
                "N'" + safeCat + "', " +
                "N'" + safeSubcat + "', " +
                (isUrgently ? 1 : 0) + ", " +
                (isLearning ? 1 : 0) + ", " +
                (isGeneral ? 1 : 0) + ", " +
                (isToday ? 1 : 0) + ", " +
                (isToBuy ? 1 : 0) + ", " +
                "0, 0, " +
                "'" + created + "', " +
                (deadline == null || deadline.isEmpty() ? "NULL" : "'" + deadline + "'") +
                ");";
    }

    public static String insertMealToCalendarTable(
            String dayDate, String dayName, String mealName, double amountOfProduct,
            String productName, double kcal, double protein, double fat, double carbs,
            String timeOptional, String commentOptional, double kcalConsume,
            double carbsConsume, double fatConsume, double proteinConsume) {

        String autoGeneratedId = java.util.UUID.randomUUID().toString();

        return insertMealToCalendarTable(
                dayDate, dayName, mealName, amountOfProduct, productName,
                kcal, protein, fat, carbs, timeOptional, commentOptional,
                kcalConsume, carbsConsume, fatConsume, proteinConsume,
                autoGeneratedId
        );
    }

    public static String insertMealToCalendarTable(
            String dayDate, String dayName, String mealName, double amountOfProduct,
            String productName, double kcal, double protein, double fat, double carbs,
            String timeOptional, String commentOptional, double kcalConsume,
            double carbsConsume, double fatConsume, double proteinConsume,
            String rowId) {

        String sqlDayDate = (dayDate == null || dayDate.trim().isEmpty())
                ? "NULL" : "'" + dayDate.replace("'", "''") + "'";
        String sqlDayName = (dayName == null || dayName.trim().isEmpty())
                ? "NULL" : "'" + dayName.replace("'", "''") + "'";
        String sqlMealName = (mealName == null || mealName.trim().isEmpty())
                ? "NULL" : "'" + mealName.replace("'", "''") + "'";
        String sqlProductName = (productName == null || productName.trim().isEmpty())
                ? "NULL" : "'" + productName.replace("'", "''") + "'";
        String sqlTime = (timeOptional == null || timeOptional.equalsIgnoreCase("none") || timeOptional.trim().isEmpty())
                ? "NULL" : "'" + timeOptional.replace("'", "''") + "'";
        String sqlComment = (commentOptional == null || commentOptional.equalsIgnoreCase("none") || commentOptional.trim().isEmpty())
                ? "NULL" : "'" + commentOptional.replace("'", "''") + "'";
        String sqlRowId = (rowId == null || rowId.trim().isEmpty())
                ? "NULL" : "'" + rowId.replace("'", "''") + "'";

        return "INSERT INTO [diet_tracker_schema].[calendar]\n" +
                "([day_date], [day_name], [meal_name], [amount_of_product], [product_name],\n" +
                "[kcal], [protein], [fat], [carbs], [time_optional], [comment_optional],\n" +
                "[kcal_consume], [carbs_consume], [fat_consume], [protein_consume], [row_id])\n" +
                "VALUES (\n" +
                sqlDayDate + ",\n" +
                sqlDayName + ",\n" +
                sqlMealName + ",\n" +
                amountOfProduct + ",\n" +
                sqlProductName + ",\n" +
                kcal + ",\n" +
                protein + ",\n" +
                fat + ",\n" +
                carbs + ",\n" +
                sqlTime + ",\n" +
                sqlComment + ",\n" +
                kcalConsume + ",\n" +
                carbsConsume + ",\n" +
                fatConsume + ",\n" +
                proteinConsume + ",\n" +
                sqlRowId + "\n" +
                ");\n" +
                "SELECT 1 AS success;";
    }

    public static String updateNoteQuery(long id, String title, String subtitle, String description,
                                         String category, String subcategory,
                                         boolean isUrgently, boolean isLearning, boolean isGeneral,
                                         boolean isToday, boolean isToBuy, String deadline) {

        String safeTitle = title != null ? title.replace("'", "''") : "";
        String safeSub = subtitle != null ? subtitle.replace("'", "''") : "";
        String safeDesc = description != null ? description.replace("'", "''") : "";
        String safeCat = category != null ? category.replace("'", "''") : "";
        String safeSubcat = subcategory != null ? subcategory.replace("'", "''") : "";

        return "SET NOCOUNT ON; " +
                "UPDATE [diet_tracker_schema].[notes] SET " +
                "[title] = N'" + safeTitle + "', " +
                "[subtitle] = N'" + safeSub + "', " +
                "[description] = N'" + safeDesc + "', " +
                "[category] = N'" + safeCat + "', " +
                "[subcategory] = N'" + safeSubcat + "', " +
                "[is_urgently] = " + (isUrgently ? 1 : 0) + ", " +
                "[is_learning] = " + (isLearning ? 1 : 0) + ", " +
                "[is_general_to_do] = " + (isGeneral ? 1 : 0) + ", " +
                "[is_today_task] = " + (isToday ? 1 : 0) + ", " +
                "[is_to_buy_task] = " + (isToBuy ? 1 : 0) + ", " +
                "[date_deadline] = " + (deadline == null || deadline.isEmpty() ? "NULL" : "'" + deadline + "'") + " " +
                "WHERE [id] = " + id + "; SELECT 1 AS success;";
    }
}